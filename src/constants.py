PIXEL_WINDOW_FORMAT = "(r0, r1, c0, c1)_half_open"

# ---------------------------------------------------------------------------
# 叠加渲染（简报 §3.8；§12：训练和评测用同一套颜色、透明度、轮廓线）
# ---------------------------------------------------------------------------

# 第 k 个 mask 用第 k 种颜色（RGB）。颜色数不够时 render_overlay 报错，不循环复用。
# 依据：Sasha Trubetskoy "List of 20 Simple, Distinct Colors"（2017）前 10 色，保持原顺序。
# 两两 CIE76 色差 ≥ 25（最近的一对是紫与品红，约 29），由 tests/test_overlay.py 钉住。颜色个数与顺序暂定。
OVERLAY_PALETTE = (
    (230, 25, 75),  # 红
    (60, 180, 75),  # 绿
    (255, 225, 25),  # 黄
    (67, 99, 216),  # 蓝
    (245, 130, 49),  # 橙
    (145, 30, 180),  # 紫
    (66, 212, 244),  # 青
    (240, 50, 230),  # 品红
    (191, 239, 69),  # 黄绿
    (250, 190, 212),  # 粉
)

# alpha = OVERLAY_ALPHA_NUM / OVERLAY_ALPHA_DEN。用整数有理数表示，混合可以全程整数运算，任何机器上逐位相同。
# mask 内的像素逐通道取 (原值*(DEN-NUM) + 颜色*NUM + DEN//2) // DEN，即四舍五入，恰为 .5 时进位。
# 依据：alpha=0.5 与 Detectron2 Visualizer.draw_binary_mask 的默认值、LISA chat.py 的可视化相同；暂定。
OVERLAY_ALPHA_NUM = 1
OVERLAY_ALPHA_DEN = 2

# 轮廓 = mask 减去"3×3 全 1 核腐蚀 OVERLAY_CONTOUR_WIDTH 次"的结果，图外按背景，画成该 mask 颜色的实色。
# 宽度 1 就是任务书的定义（mask 减 3×3 腐蚀）。依据：DEV-0002 任务书。
# 宽度 2 为暂定：图像进视觉编码器前会缩放（见 docs/model_notes.md），1 px 的线缩小后会变淡。
OVERLAY_DRAW_CONTOUR = True
OVERLAY_CONTOUR_WIDTH = 2

# ---------------------------------------------------------------------------
# 分块与拼接（E3c 局部阶段，简报 §8.6）
# ---------------------------------------------------------------------------

# 块边长与重叠（像素，原分辨率）。块起点按 mmsegmentation EncoderDecoder.slide_inference 的规则：
# 步长 = TILE_SIZE - TILE_OVERLAP，块数 = max(边长 - TILE_SIZE + 步长 - 1, 0) // 步长 + 1，
# 最后一块贴边对齐，不填充；图比块小时整张图就是一块。
# 拼接与 mmseg 的 preds / count_mat 在数学上相同（重叠处按覆盖块数平均），数值上改为逐块增量平均，见 stitch。
# 数值暂定：256 是 32 的倍数（Qwen3.5 每个 LLM 视觉 token 对应缩放后图像的 32×32 px，见 docs/model_notes.md），
# 一块 8×8 个 token；重叠 64 px 即 2 个 token，步长 192。
TILE_SIZE = 256
TILE_OVERLAP = 64

# ---------------------------------------------------------------------------
# 无学习上采样（简报 §4 第 2 条白名单；§8.4 默认用引导上采样，同时报告双线性）
# ---------------------------------------------------------------------------

# 引导滤波（He, Sun, Tang, ECCV 2010 / TPAMI 2013）。guided_upsample 用这组值。
# 半径以输出分辨率的像素计；eps 以引导图归一化到 [0, 1] 之后的方差计（uint8 图除以 255）。
# 数值暂定：同一组值要同时服务 E3b（32×32 网格放大到 480×640 是 15–20 倍）与 E3a（128×128 放大 3.75–5 倍）。
# 半径 8 即窗口 17 px，约为 32×32 网格在 640 宽图上的一个格子（20 px）；eps 对应局部标准差约 0.03，
# 弱于它的纹理被抹平、强于它的边缘被保留。
# 只在 DEV-0002 的合成场景上做过合理性检查（不是在任何真实数据上调参），在真实开发子集上定稿。
GUIDED_FILTER_RADIUS = 8
GUIDED_FILTER_EPS = 1e-3

# 联合双边上采样（Kopf, Cohen, Lischinski, Uyttendaele, SIGGRAPH 2007）。
# 空间高斯 sigma 与窗口半径以低分辨率像素计（半径 2 即 5×5 个低分辨率像素，截断在 ±2 sigma）；
# 值域高斯 sigma 以 [0, 1] 引导图计。数值暂定：sigma_range 取 0.2 而不是 0.1，因为 Ĩ_q 是单个像素的取值，
# 对纹理和噪声敏感，合成场景里 0.1 在 32×32 → 480×640 时反而不如双线性；0.2 在两种放大倍数下都优于双线性
# （tests/test_uncertainty.py 的彩排钉住）。在真实开发子集上定稿。
JBU_SIGMA_SPATIAL = 1.0
JBU_SIGMA_RANGE = 0.2
JBU_RADIUS = 2

# ---------------------------------------------------------------------------
# 不确定度选区（E3b 边界细化，简报 §8.5；N8：mask 与深度统一按熵选）
# ---------------------------------------------------------------------------

# 每张图选的区域数、正方形区域边长（像素，按传入的概率图分辨率计）。
# 数值暂定：64 px 在 640 宽的图上约为 32×32 网格的 3 个格子。
UNCERTAINTY_NUM_REGIONS = 4
UNCERTAINTY_REGION_SIZE = 64

# 逐像素熵（nats）先量化成 UNCERTAINTY_ENTROPY_QUANTUM 的整数倍，再用整数求窗口和：
# 内容相同的两个窗口得分严格相等，平局一律按固定规则打破，与求和顺序无关。
# 取 2 的幂，除法无舍入误差。
UNCERTAINTY_ENTROPY_QUANTUM = 2.0**-32
# 多类输入每个像素的概率和须落在 1 ± 这个容差内，否则报错，不静默归一化。
UNCERTAINTY_PROB_SUM_ATOL = 1e-6

# ---------------------------------------------------------------------------
# mask 加噪过程（E3b 的"带错 → 正确"训练对，简报 §3.7 第 2 条）
# ---------------------------------------------------------------------------

# 噪声日程：以概率 MASK_NOISE_P_CLEAN 取 s = 0（干净对：mask 已经正确时应原样输出，即叠加反馈的不动点），
# 否则 s ~ Beta(MASK_NOISE_SEVERITY_BETA)。Beta(1, 1) 即 [0, 1] 均匀，
# 对应 DDPM 训练时时间步均匀采样（Ho et al. 2020, Algorithm 1）。两项都暂定。
MASK_NOISE_P_CLEAN = 0.1
MASK_NOISE_SEVERITY_BETA = (1.0, 1.0)

# 每次 corrupt 施加的算子个数在 1..MASK_NOISE_MAX_OPS 里均匀取（不超过可用算子数）。暂定。
MASK_NOISE_MAX_OPS = 3

# 各算子的强度：长度单位 L = sqrt(原 mask 面积)（像素），扰动量 = s × 系数 × L，s ∈ [0, 1]。
# 用物体自身的尺度，使同一个 s 对大小不同的物体造成相近的 IoU 损失。
# 系数暂定，按一条规则标定：s = 1 时单个算子作用于 96×160 图里半径 25 px 的圆盘，平均 IoU ≈ 0.5
# （tests/test_mask_noise.py 钉住 [0.45, 0.55]）。合并不在此列：它的损失取决于邻近物体的大小。
MASK_NOISE_ERODE_MAX = 0.17  # 腐蚀半径
MASK_NOISE_DILATE_MAX = 0.24  # 膨胀半径
MASK_NOISE_JITTER_AMP_MAX = 0.3  # 边界抖动幅度（平滑随机场归一化到单位标准差后乘以它）
MASK_NOISE_JITTER_SMOOTH = 0.1  # 抖动场的高斯平滑 sigma（与 s 无关）
MASK_NOISE_BLOB_RADIUS_MAX = 0.5  # 增删的圆形区域半径（再乘以 [0.5, 1) 的随机因子）
MASK_NOISE_BLOB_COUNT = (1, 3)  # 增删区域个数的闭区间（与 s 无关）
MASK_NOISE_BLOB_BAND = 0.5  # 新增区域的圆心距物体不超过 系数 × L（与 s 无关）
MASK_NOISE_SHIFT_MAX = 0.3  # 平移距离
MASK_NOISE_MERGE_MAX = 1.0  # 并入最近邻物体的像素比例（按到本物体的距离由近到远取）
